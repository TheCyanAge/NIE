/**
 * GENRE add-ons, part B: fantasy and science fiction. Epic, urban and dark fantasy, fairy-tale retellings, portal fantasy, sword and sorcery, space
 * opera, hard science fiction, cyberpunk, dystopian fiction, post-apocalyptic fiction, time travel, first contact and alternate history. Each add-on
 * encodes what readers of THE GENRE expect and what its writer has to decide (the promises it makes, the conventions it may keep or break), and is
 * merged into the kind packs listed in `baseKinds` when the writer's words match.
 *
 * The questions follow the same rules as the kind packs, plus these:
 *  - A slot is only asked while it is EMPTY, so no question leans on something the writer has not said. A part the genre usually has but this story
 *    may not (a prophecy, a chosen one, a paradox, a rebellion, a happy ending) is asked as a possibility, never as a fact, and no question assumes
 *    a villain, a twist, a romance or a hopeful ending beyond what the genre's name already promises.
 *  - The conventions are asked about, never enforced: "does the story keep this rule or knowingly bend it?" is a question, not a rule. Only the
 *    writer's own choices count.
 *  - {who}, {place}, {thing}, {genre}, {kind} and {theme} are the placeholders used, each only where the neutral fallback ("your main character",
 *    "your setting", "your idea", "your genre", "project", "your theme") still reads correctly; {want} and {other} are left out because a writer's
 *    phrase for them rarely fits a sentence. A slot whose value is a person, a place or a theme never uses the placeholder for that same thing.
 *  - Where the base kind may be a script, "audience" is said instead of "reader"; where it may be a world, nothing assumes a single hero. The
 *    fairy-tale retelling also covers a poem, so it says "someone who knows the old tale".
 *  - Slot ids start with the add-on's id, because several add-ons can apply to one idea at once and their slot ids must never collide.
 *  - Hints stay within the first 120 characters, which is all the extractor shows the model.
 *  - Questions only ask about the idea. They never draft a scene, a line, a name or a twist for the writer, and never name a real work or person.
 */

