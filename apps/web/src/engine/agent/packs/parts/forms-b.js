/**
 * FORM add-on packs, part B: verse (sonnet, haiku, villanelle, ballad, epic poem, verse novel), short prose (flash fiction, short story, novella)
 * and visual or young-reader books (picture book, graphic novel, children's chapter book).
 *
 * A form add-on says how the FORM works: its length, its structure, how it is delivered, what it can and cannot do, what its audience expects. Each slot
 * is asked while it is still empty, so no question assumes the writer has already answered it, and none uses the placeholder for the slot's own contents.
 * Slot ids start with the add-on's full id, because several add-ons can apply to one idea at once and their slot ids must never collide.
 * Questions only ask about the idea. They never draft a line, a verse, a title or a panel for the writer, and they never assume a villain, a twist,
 * a romance or a happy ending. Words a writer may not know (refrain, tercet, panel, spread) are glossed in the question itself.
 */

