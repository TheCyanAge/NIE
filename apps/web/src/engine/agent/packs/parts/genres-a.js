/**
 * GENRE add-ons, part A: mystery, crime, thriller and horror. A cozy mystery, a locked-room mystery, hardboiled noir, a police procedural, a
 * psychological thriller, a spy thriller, a legal thriller, a heist story, a gangster saga, gothic, a ghost story, folk horror, cosmic horror and a
 * slasher. Each add-on encodes what readers of THE GENRE expect and what its writer has to decide (the promises it makes, the conventions it may keep
 * or break), and is merged into the kind packs listed in `baseKinds` when the writer's words match.
 *
 * The questions follow the same rules as the kind packs, plus these:
 *  - A slot is only asked while it is EMPTY, so no question leans on something the writer has not said. A part the genre usually has but this story
 *    may not (a twist, a ghost that is seen, a trial, a second plan) is asked as a possibility, never as a fact, and no question assumes a villain,
 *    a twist, a romance or a happy ending beyond what the genre's name already promises.
 *  - The conventions are asked about, never enforced: "does the story follow the rules of the genre or knowingly play against them?" is a question,
 *    not a rule. Only the writer's own choices count.
 *  - {who}, {place}, {thing} and {genre} are the only placeholders used, each where the neutral fallback ("your main character", "your setting",
 *    "your idea", "your genre") still reads correctly; {want} and {other} are left out because a writer's phrase for them rarely fits a sentence.
 *    {kind} is used where gothic also covers a poem. Where the base kind may be a script, "audience" is said instead of "reader".
 *  - Slot ids start with the add-on's id (or its first word where the full id would make a slot id too long), because several add-ons can apply to one
 *    idea at once and their slot ids must never collide.
 *  - Hints stay within the first 120 characters, which is all the extractor shows the model.
 *  - Questions only ask about the idea. They never draft a clue, a line, a scene or a twist for the writer, and never name a real work or person.
 */

