/**
 * GENRE add-ons, part C: love stories and history, plus a run of broad story genres. Contemporary and historical romance, romantic comedy,
 * historical fiction, the western, the war story, the coming-of-age story, magical realism, satire, the family saga, the survival story,
 * the adventure quest, slice of life and tragedy. Each add-on encodes what readers of THE GENRE expect and what its writer has to decide
 * (the promises it makes, the conventions it may keep or break), and is merged into the kind packs listed in `baseKinds` when the writer's
 * words match.
 *
 * The questions follow the same rules as the kind packs, plus these:
 *  - A slot is only asked while it is EMPTY, so no question leans on something the writer has not said. A part the genre usually has but this
 *    story may not (a pretence, a showdown, a real person on the page, a rescue) is asked as a possibility, never as a fact, and no question
 *    assumes a villain, a twist or a happy ending beyond what the genre's own name already promises. The conventions are asked about, never
 *    enforced: "does the story keep this rule or knowingly bend it?" is a question, not a rule. Only the writer's own choices count.
 *  - {who}, {place}, {thing}, {kind}, {want}, {other} and {theme} are used only where the neutral fallback ("your main character", "your
 *    setting", "your idea", "project", "what they want", "whoever stands in their way", "your theme") still reads correctly, and never right
 *    after the, a, an, your or their. {genre} is used rarely and only as "In {genre}": with two genres on one idea it names the first one.
 *  - Where the base kind may be a script, "audience" is said instead of "reader". Satire also covers an essay and an article, so it says "the
 *    piece" and never uses {who} or {place} (those packs have no such slot). Tragedy also covers a poem, where {who} would be the speaker, so
 *    it never uses {who} either.
 *  - Slot ids start with the add-on's id, because several add-ons can apply to one idea at once and their slot ids must never collide.
 *  - Hints stay within the first 120 characters, which is all the extractor shows the model.
 *  - Questions only ask about the idea. They never draft a scene, a line, a name or a twist for the writer, and never name a real work or person.
 */

