/**
 * FORM add-ons, part C: long, serial, nonfiction and interactive forms (a web serial, fan fiction, a story told in letters, a diary, a personal essay,
 * a memoir, travel writing, long-form journalism, an op-ed, a how-to guide, a biography, interactive fiction, a tabletop campaign).
 *
 * A form add-on says how the FORM works: how it is delivered, how long and how built, what it can and cannot do, and what its readers expect.
 * It never repeats the kind pack, and every question only asks about the writer's idea: nothing here drafts, rewrites or invents text for the writer.
 * The same rules as the kind packs hold: a slot is asked while it is still empty, so a question never presumes the slot's own answer; a placeholder
 * is used only where the sentence still reads with its neutral fallback ({who} only in forms that are stories, because an essay or an article has no
 * main character); and slot ids start with the add-on's id so that several add-ons can apply to one idea without clashing.
 */

