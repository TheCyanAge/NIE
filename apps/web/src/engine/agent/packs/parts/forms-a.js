/**
 * FORM add-ons, part A: performance and audio. A song, a spoken-word piece, a speech, a toast or eulogy, a stage play, a monologue, an audio drama,
 * a podcast, a sketch, a stand-up set, a feature screenplay and a TV series. Each add-on encodes how THE FORM works (how it is delivered, how long it
 * runs, what it can and cannot do, what its audience expects) and is merged into the kind packs listed in `baseKinds` when the writer's words match.
 *
 * The questions follow the same rules as the kind packs, plus these:
 *  - A slot is asked while it is still empty, so a question never leans on something the writer has not said ("the chorus", "the twist"). Where a part
 *    may not exist it asks whether it does ("If the song has a part that returns...").
 *  - {who} (the main character) only exists when the base kind is a script, and {thing} is only used after a preposition ("a speech about {thing}"),
 *    where a title, a topic or the neutral fallback all read correctly. A form such as a speech has no main character, so it never uses {who}.
 *  - Craft words the writer may not use (bridge, callback, button, pilot, showrunner) are glossed inside the question, in plain speech.
 *  - Questions only ask about the idea. They never ask for a line, a joke, a verse or a scene, and never offer one.
 */

/** [type, text] rows are easier to read and to review than a wall of braces; the pack still exports plain { text, type } objects. */
