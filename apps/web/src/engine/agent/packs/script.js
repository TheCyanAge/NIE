/**
 * SCRIPT pack: screen, stage and audio. What NIE wants to understand about a writer's script, in the order a conversation tends to go, and a bank of
 * questions for each part. It assumes no genre, no medium and no villain: "audience" covers someone watching, sitting in a theatre or only listening.
 * Questions only ask about the idea; they never draft a line of dialogue, a scene or a title for the writer.
 *
 * Three rules these questions follow because of how the agent uses them:
 *  - A slot is only asked while it is EMPTY, and the answer is filed whole. So every question in a slot asks for the thing itself and never leans on
 *    something the writer has not said yet ("get it", "this scene", "the obstacle"), and the slots that fill a placeholder ({who}, {place}) never use
 *    their own placeholder (it could only ever show the neutral fallback).
 *  - {thing} is whatever short phrase the writer gave for the premise: a title, a topic, or nothing (then "your idea"). It is only ever used after a
 *    preposition ("a script about {thing}"), where all three read correctly; the script itself is always "the script".
 *  - Craft words the writer may not use ("motif") are glossed in plain speech.
 */

