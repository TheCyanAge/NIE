/**
 * STORY pack: what NIE wants to understand about a writer's story, in the order a conversation tends to go, and a bank of questions for each part.
 * It assumes no genre: a genre or form the writer names adds its own slots from the add-on packs. Questions only ask about the idea; they never
 * draft anything for the writer, never assume a villain, a romance, a twist or a happy ending.
 *
 * Three things the validator cannot see, and the questions are written for:
 *  - A slot is asked while it is still EMPTY. So a question never uses the placeholder that stands for its own slot (it could only show the neutral
 *    fallback), never refers to "the obstacle" or "it" as if the writer had named one, and in a slot the writer may not have at all (an opposing
 *    person, a recurring image) it asks whether there is one.
 *  - What the writer answers is recorded whole under the slot, and for the main character it becomes {who} in the questions that follow. So every
 *    question in "Main character" asks who the person is, not what they are like: "She rushes in" must never turn into "What does the rushes in want?".
 *  - The extractor shows the model only the first 120 characters of a hint, so a hint says what the slot is within that.
 */

