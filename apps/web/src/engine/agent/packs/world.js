/**
 * WORLD pack: what NIE wants to understand about a world a writer is building (a realistic place, an alternate one, an invented one), in the order
 * a conversation tends to go. No genre is assumed: "technology or magic" is one slot because the writer decides which it is. Questions ask what the
 * world is and how it behaves; they never invent a rule, a name or a history for the writer.
 *
 * It uses NO placeholders, on purpose. The only one that could stand for this world is {place}, which the engine fills from the "Places and geography"
 * slot, and a writer answers that with a LIST ("Three kingdoms: Aldmere, the Salt Reach and the Ash Coast", "There's the capital on the coast and...").
 * The engine cuts a list down to its first words, so {place} came out as "Three", "Nine", "There's" or "the city built", and the picker prefers a
 * question whose placeholders are all known, so it would have asked those first. "This world" says the same thing and cannot go wrong.
 *
 * A slot is asked while it is still EMPTY, so a question never refers to "the cost" or "that power" as if the writer had named one, and in the
 * slots a world may not have (a price to pay, hidden truths, a feared people) it asks whether there is one.
 */

