/**
 * CHARACTER pack: what NIE wants to understand about one person a writer is building, in the order a conversation tends to go.
 * No genre or world is assumed (a detective, a dragon and a grandmother all fit these questions): nothing here needs a calendar, a pocket, a wage or
 * a dinner table. The questions ask about the person and never hand the writer a trait, a line of speech or a backstory: the answers must be the
 * writer's own. About half use the character's name or description when NIE has it; the rest say "this character" so they still read naturally
 * before NIE knows who it is.
 *
 * Written for how the agent really uses a pack: a slot is asked while it is still EMPTY, so a question about a secret or a flaw asks whether there
 * is one and never says "the secret" or "the flaw" as if the writer had named it; and what the writer answers to "Who they are in the story" becomes
 * {who} in every later question, so each question in that slot asks who the character is, not what they are like.
 */

