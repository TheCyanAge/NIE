/**
 * CHARACTER pack: what NIE wants to understand about one person a writer is building, in the order a conversation tends to go.
 * No genre is assumed (a detective, a dragon and a grandmother all fit these questions). The questions ask about the person and never
 * hand the writer a trait, a line of speech or a backstory: the answers must be the writer's own. About half use the character's name or
 * description when NIE has it; the rest say "this character" so they still read naturally before NIE knows who it is. A slot is asked while
 * it is still EMPTY, so the questions about a secret or a flaw ask whether there is one rather than taking it for granted.
 */

