// Regenerates apps/web/src/engine/knowledge/library/index.js from the data files next to it.
//   node scripts/build-library-index.mjs          # write
//   node scripts/build-library-index.mjs --check  # exit 1 if the index is out of date
// Each data file is imported lazily so the library can be loaded after the app's first paint.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LIB_DIR = path.join(root, 'apps/web/src/engine/knowledge/library');

export function listDataFiles(dir = LIB_DIR) {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.js') && !(d === dir && e.name === 'index.js')) out.push(path.relative(dir, p).split(path.sep).join('/'));
    }
  };
  walk(dir);
  return out.sort();
}

export function renderIndex(files = listDataFiles()) {
  const lib = files.filter((f) => !f.startsWith('enrich/'));
  const enr = files.filter((f) => f.startsWith('enrich/'));
  const line = (f) => `  () => import('./${f}'),`;
  return `// GENERATED by scripts/build-library-index.mjs. Do not edit by hand.
export const LIBRARY_FILES = [
${lib.map(line).join('\n')}
];
export const ENRICH_FILES = [
${enr.map(line).join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = path.join(LIB_DIR, 'index.js');
  const next = renderIndex();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== next) {
      console.error('library/index.js is out of date. Run: node scripts/build-library-index.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, next);
    console.log(`library/index.js: ${listDataFiles().length} data files`);
  }
}
